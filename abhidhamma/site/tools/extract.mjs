// Renders the atlas once in Chromium and saves its DRAWINGS for the site: the idea pictures,
// the plate drawings, the concept map, their animations and the colour tokens.
// It writes no text: every word on the site lives in src/content/, so re-running this
// can never overwrite an edit.
// Run it again whenever the atlas changes: npm run extract
import { createRequire } from "node:module";
import { execSync } from "node:child_process";
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const require = createRequire(import.meta.url);
let chromium;
try { ({ chromium } = require("playwright")); }
catch { ({ chromium } = require(path.join(execSync("npm root -g").toString().trim(), "playwright"))); }

const here = path.dirname(fileURLToPath(import.meta.url));
const atlas = path.resolve(here, "../../atlas/index.html");
const out = path.resolve(here, "../src/data");

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
page.on("pageerror", (e) => console.warn("atlas page error:", e.message));
await page.route(/^https?:/, (r) => r.abort()); // fonts and three.js are not needed here
await page.goto(pathToFileURL(atlas).href, { waitUntil: "load" });
await page.waitForTimeout(800);

const result = await page.evaluate(() => {
  const clean = (svg) => { const c = svg.cloneNode(true); c.removeAttribute("width"); c.removeAttribute("height"); return c.outerHTML; };
  const pictures = {};
  document.querySelectorAll("#ideas .idea, #ideas-2 .idea").forEach((el) => {
    const a = el.querySelector("a.ilink"); const svg = el.querySelector("figure svg");
    const id = a && a.getAttribute("href").replace("#idea-", "");
    if (id && svg) pictures[id] = { svg: clean(svg), caption: el.querySelector("figcaption")?.textContent || "" };
  });
  const plates = {};
  document.querySelectorAll("section.sheet[id^=p]").forEach((s) => {
    // The plate's main drawing is its largest svg.
    const svgs = [...s.querySelectorAll("svg")].filter((v) => !v.closest(".nav, .tocp"));
    const svg = svgs.sort((a, b) => b.outerHTML.length - a.outerHTML.length)[0];
    if (svg && svg.outerHTML.length > 2000) plates[s.id] = clean(svg);
  });
  const map = document.querySelector("#map svg.cmap").outerHTML;
  return { pictures, plates, map };
});
await browser.close();

writeFileSync(path.join(out, "pictures.json"), JSON.stringify(result.pictures));
writeFileSync(path.join(out, "plates.json"), JSON.stringify(result.plates));
writeFileSync(path.join(out, "map.json"), JSON.stringify({ svg: result.map }));
console.log("ideas pictured:", Object.keys(result.pictures).length, "plates:", Object.keys(result.plates).length);

// The site draws with the atlas's own colours: copy its tokens (light and dark) and the svg text classes.
const css = readFileSync(path.resolve(here, "../../atlas/atlas.css"), "utf8");
const tokens = css.slice(css.indexOf(":root {"), css.indexOf("* { box-sizing"));
const svgClasses = css.slice(css.indexOf("/* svg utility classes */"), css.indexOf("/* ---------- cover"));
mkdirSync(path.resolve(here, "../src/styles"), { recursive: true });
writeFileSync(path.resolve(here, "../src/styles/atlas-tokens.css"),
  "/* Generated by tools/extract.mjs from ../atlas/atlas.css. Do not edit. */\n" + tokens + "\n" + svgClasses);

const maps = readFileSync(path.resolve(here, "../../atlas/js/maps.js"), "utf8");
console.log("tokens written");


// The idea pictures' animations (maps.js) as a standalone script for the concept pages.
{
  const a = maps.indexOf("  var animatePicture = (function ()"), b = maps.indexOf("  window.ATLAS.animatePicture = animatePicture;");
  const helpers = maps.slice(maps.indexOf("  function A(o)"), maps.indexOf("  function $(id)"));
  const js = "/* Generated by tools/extract.mjs from ../atlas/js/maps.js: the idea pictures' teaching motions. */\n(function () {\n  \"use strict\";\n" +
    helpers + maps.slice(a, b).replace(/\n  window\.ATLAS = window\.ATLAS \|\| \{\};\n  window\.ATLAS\.ideaPicture = PIC;/, "") +
    "  document.addEventListener(\"click\", function (e) {\n    var b = e.target.closest && e.target.closest(\"[data-play]\"), svg = b ? document.querySelector('svg.ipic[data-id=\"' + b.getAttribute(\"data-play\") + '\"]') : e.target.closest && e.target.closest(\"svg.ipic\");\n    if (svg) animatePicture(svg, svg.getAttribute(\"data-id\"));\n  });\n})();\n";
  mkdirSync(path.resolve(here, "../public/js"), { recursive: true });
  writeFileSync(path.resolve(here, "../public/js/pictures.js"), js);
  console.log("pictures.js written");
}
